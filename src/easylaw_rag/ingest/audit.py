"""Data-quality audit of the EasyLaw corpus. Writes a Markdown report.

Usage:
    python -m easylaw_rag.ingest.audit --data data/interim --out docs/data_audit.md
"""

from __future__ import annotations

import argparse
import hashlib
import random
import re
from collections import Counter
from pathlib import Path

import pandas as pd

from easylaw_rag.text.arabic import (
    ARABIC_LETTER_RE,
    LATIN_LETTER_RE,
    MOJIBAKE_RE,
    arabic_words,
    normalize,
)

ARTICLE_RE = re.compile(r"(?:^|\s)الماده\s+(?:\d+|الاولي|الاول|الوحيده)")
RARE_MAX_FREQ = 2  # a word seen <= 2 times in 300M chars is almost always OCR noise


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def md_table(df: pd.DataFrame) -> str:
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join(str(v) for v in row) + " |")
    return "\n".join(lines)


def title_coverage(desc_words: list[str], text_words: set[str]) -> float:
    if not desc_words:
        return float("nan")
    return sum(w in text_words for w in desc_words) / len(desc_words)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data", type=Path, default=Path("data/interim"))
    ap.add_argument("--out", type=Path, default=Path("docs/data_audit.md"))
    ap.add_argument("--seed", type=int, default=7)
    args = ap.parse_args()
    rng = random.Random(args.seed)

    jt = pd.read_parquet(args.data / "juridical_texts.parquet")
    oj = pd.read_parquet(args.data / "official_journals.parquet")
    adj = pd.read_parquet(args.data / "adjustments.parquet")

    jt["year"] = jt["publication_date"].dt.year
    jt["decade"] = (jt["year"] // 10 * 10).astype("Int64").astype(str) + "s"
    text = jt["extracted_text"].fillna("")
    jt["has_text"] = text.str.strip().str.len() > 0
    jt["text_len"] = text.str.len()

    # ---------- encoding ----------
    print("encoding checks...")
    jt["n_replacement"] = text.str.count("�")
    jt["mojibake"] = text.str.contains(MOJIBAKE_RE)
    ar = text.str.count(ARABIC_LETTER_RE.pattern)
    la = text.str.count(LATIN_LETTER_RE.pattern)
    jt["arabic_ratio"] = (ar / (ar + la).where(ar + la > 0)).fillna(0)

    # ---------- page-level duplication ----------
    jt["text_hash"] = text.map(lambda t: hashlib.md5(t.encode()).hexdigest() if t else None)
    share = jt.groupby("text_hash")["id_text"].transform("count")
    jt["shared_with"] = share.where(jt["has_text"], 0).fillna(0).astype(int) - 1

    # ---------- tokenization (unique texts only) ----------
    print("tokenizing corpus (a few minutes)...")
    uniq = jt[jt["has_text"]].drop_duplicates("text_hash")
    freq: Counter[str] = Counter()
    for t in uniq["extracted_text"]:
        freq.update(arabic_words(t))
    print(f"  vocabulary: {len(freq):,} distinct normalized words")

    print("per-document metrics...")
    rare_rate, cover, n_articles, rare_examples = {}, {}, {}, {}
    for row in jt[jt["has_text"]].itertuples():
        words = arabic_words(row.extracted_text)
        if words:
            rare = [w for w in words if freq[w] <= RARE_MAX_FREQ]
            rare_rate[row.Index] = len(rare) / len(words)
            if rare:
                rare_examples[row.Index] = rare[:8]
        else:
            rare_rate[row.Index] = 1.0
        cover[row.Index] = title_coverage(arabic_words(row.description or ""), set(words))
        n_articles[row.Index] = len(ARTICLE_RE.findall(normalize(row.extracted_text)))
    jt["rare_rate"] = pd.Series(rare_rate)
    jt["title_cov"] = pd.Series(cover)
    jt["n_articles"] = pd.Series(n_articles)

    # ---------- descriptions ----------
    desc_freq: Counter[str] = Counter()
    for d in jt["description"].fillna(""):
        desc_freq.update(arabic_words(d))
    desc_in_corpus = sum(c for w, c in desc_freq.items() if freq[w] > RARE_MAX_FREQ) / max(
        1, sum(desc_freq.values())
    )

    # ---------- amendment graph ----------
    ids = set(jt["id_text"])
    pub = jt.set_index("id_text")["publication_date"]
    adj["adjusted_known"] = adj["adjusted_num"].isin(ids)
    adj["adjusting_known"] = adj["adjusting_num"].isin(ids)
    both = adj[adj["adjusted_known"] & adj["adjusting_known"]].copy()
    both["later"] = both["adjusting_num"].map(pub) >= both["adjusted_num"].map(pub)

    # ---------- report ----------
    has = jt[jt["has_text"]]
    lines: list[str] = []
    w = lines.append
    w("# EasyLaw corpus — data audit\n")
    w("Generated by `python -m easylaw_rag.ingest.audit`. Source: the three MySQL dumps of the original EasyLaw platform.\n")

    w("## 1. Volume\n")
    w(f"- Juridical texts: **{len(jt):,}** ({jt['year'].min()}–{jt['year'].max()})")
    w(f"- With OCR text: **{len(has):,}** ({pct(len(has) / len(jt))}); total {jt['text_len'].sum() / 1e6:.0f}M characters")
    w(f"- Distinct OCR texts: **{jt['text_hash'].nunique():,}** (rows sharing an identical text: {pct((has['shared_with'] > 0).mean())})")
    w(f"- Official journals: **{len(oj):,}** ({oj['year'].min()}–{oj['year'].max()})")
    w(f"- Amendment links: **{len(adj):,}**\n")

    w("## 2. Encoding\n")
    w(f"- Unicode replacement chars (`U+FFFD`): {int(jt['n_replacement'].sum()):,} in {int((jt['n_replacement'] > 0).sum()):,} texts")
    w(f"- Mojibake (UTF-8 read as Latin-1): {int(jt['mojibake'].sum()):,} texts")
    w(f"- Median Arabic share of letters: {pct(has['arabic_ratio'].median())}; texts under 80% Arabic: {int((has['arabic_ratio'] < 0.8).sum()):,}\n")

    w("## 3. OCR quality (rare-word rate)\n")
    w(f"Share of a text's words that appear ≤{RARE_MAX_FREQ} times in the whole corpus — a proxy for OCR garbage. Lower is better.\n")
    by_dec = has.groupby("decade").agg(
        texts=("id_text", "count"),
        median_rare=("rare_rate", "median"),
        p90_rare=("rare_rate", lambda s: s.quantile(0.9)),
        median_len=("text_len", "median"),
    )
    by_dec["median_rare"] = by_dec["median_rare"].map(pct)
    by_dec["p90_rare"] = by_dec["p90_rare"].map(pct)
    by_dec["median_len"] = by_dec["median_len"].astype(int)
    w(md_table(by_dec.reset_index()) + "\n")
    w(f"- Description field: {pct(desc_in_corpus)} of description words are common corpus words → descriptions are clean (typed from the JORADP site, not OCR).\n")

    w("## 4. Does the OCR text contain the right law? (title coverage)\n")
    w("Share of the description's words found in the extracted text. Low coverage means the page OCR missed the text or the text is on another page.\n")
    tc = has["title_cov"].dropna()
    w(f"- Median coverage {pct(tc.median())}; ≥80%: {pct((tc >= 0.8).mean())}; <50%: {pct((tc < 0.5).mean())}\n")

    w("## 5. Structure by text type\n")
    by_type = jt.groupby("type_text").agg(
        texts=("id_text", "count"),
        with_text=("has_text", "mean"),
        median_len=("text_len", "median"),
        with_articles=("n_articles", lambda s: (s.fillna(0) > 0).mean()),
        median_rare=("rare_rate", "median"),
    ).sort_values("texts", ascending=False).head(15)
    for c in ("with_text", "with_articles", "median_rare"):
        by_type[c] = by_type[c].map(pct)
    by_type["median_len"] = by_type["median_len"].astype(int)
    w(md_table(by_type.reset_index()) + "\n")

    w("## 6. Amendment graph\n")
    w(md_table(adj["adjustment_type"].value_counts().rename_axis("type").reset_index()) + "\n")
    w(f"- Links whose target text is in the corpus: {pct(adj['adjusted_known'].mean())}; whose source is: {pct(adj['adjusting_known'].mean())}")
    w(f"- Direction sanity (amending text published on/after amended text): {pct(both['later'].mean())} of {len(both):,} resolvable links\n")

    w("## 7. Multi-page truncation\n")
    w("A text's page span is estimated as the pages until the next text in the same journal starts "
      "(the last text of each journal is excluded). Multi-page texts whose OCR is no longer than a "
      "typical single-page text probably only have their first page.\n")
    srt = jt.sort_values(["official_journal_id", "official_journal_page", "id_text"])
    nxt = srt.groupby("official_journal_id")["official_journal_page"].shift(-1)
    srt = srt.assign(span=(nxt - srt["official_journal_page"]).clip(lower=0) + 1)
    srt = srt[srt["has_text"] & nxt.notna()]
    one_page = srt.loc[srt["span"] == 1, "text_len"].median()
    multi = srt[srt["span"] >= 2]
    trunc = multi["text_len"] < 1.3 * one_page
    key = multi["type_text"].isin(["قانون", "قانون عضوي", "أمر", "مرسوم تشريعي"])
    w(f"- Median length of single-page texts: {int(one_page):,} chars")
    w(f"- Multi-page texts that look first-page-only: **{pct(trunc.mean())}** of {len(multi):,}")
    w(f"- Among laws / organic laws / ordinances / legislative decrees: **{pct(trunc[key].mean())}** of {int(key.sum()):,}\n")

    w("## 8. Samples of rare (likely OCR-noise) words\n")
    for dec in sorted(has["decade"].unique()):
        pool = [i for i in has[has["decade"] == dec].index if i in rare_examples]
        if pool:
            sample = rare_examples[rng.choice(pool)]
            w(f"- {dec}: " + " · ".join(sample))
    w("")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8")
    jt.drop(columns=["extracted_text"]).to_parquet(args.data / "audit_metrics.parquet", index=False)
    print(f"report -> {args.out}")


if __name__ == "__main__":
    main()
